/**
 * `EPD_RFC` — rapid fire chance. Four tenths of a point a workshop level.
 *
 * Additive vault, from the canonical dump
 * `temp/EffectivePaths-canonical.xlsx` (v5.10.02):
 *
 *     EPD_RFC: LAMBDA(ws_level, substat, vault,
 *       LET(WS, ws_level * 0.4%, WS + Substat + vault))
 *
 * Same stale WC multiplicative form as {@link multishotChance} is wrong
 * against this dump.
 */
export function rapidFireChance(workshopLevel: number, substat: number, vault: number): number {
  return workshopLevel * 0.004 + substat + vault
}

/** `EPD_RFD` — rapid fire duration in seconds, over a 0.6s base. */
export function rapidFireDuration(workshopLevel: number, substat: number): number {
  return 0.6 + workshopLevel * 0.05 + substat
}



/**
 * Bots: medals to take one bot stat from where it is to where you want it.
 *
 * A bot's four stats share one medal ladder — the cost of level 12 is the same whichever
 * stat you are buying — but each stat has its own value table. So the cost comes from the
 * bot and the effect comes from the stat, and mixing those up gives a plausible number
 * against the wrong curve.
 */
/* ── file map ─────────────────────────────────────────────────────────────────
 * exports    botUpgradeCalculator
 * depends    src/builders/types, src/data
 * used by    src/builders/index
 * ─────────────────────────────────────────────── generated by `npm run map` ──
 */
import { BOT_UPGRADES_DATA, botStatMaxLevel, findBotByName, formatBotStatValue, type BotData, type BotStatDefinition } from '../data'
import { type CalculatorBuilder, type CalculatorResultBase, clampNumber ,
  safeRecord} from './types'
import type { BotUpgradeInput, BotUpgradeLevel, BotUpgradeResult } from './types'

interface BotEntry {
  readonly key: string
  readonly label: string
  readonly statOrder: readonly string[]
  readonly costs: readonly number[]
  readonly stats: Record<string, BotStatDefinition | undefined>
}

/*
 * Read from the upgrade table rather than transcribed, so a new bot appears on its own.
 *
 * `BOT_UPGRADES_DATA` is an ARRAY, so the key here is the bot's own name — an index would
 * change meaning the moment a bot is inserted, and a saved preference would then point at
 * a different bot without anything failing.
 */
const BOTS: readonly BotEntry[] = (BOT_UPGRADES_DATA as readonly BotData[]).map(bot => ({
  key: bot.name,
  label: bot.label || bot.name,
  statOrder: bot.statOrder ?? [],
  costs: bot.costs ?? [],
  stats: (bot.stats ?? {}) as Record<string, BotStatDefinition | undefined>,
}))

const firstBot = BOTS[0]
const defaults: BotUpgradeInput = {
  bot: firstBot?.key ?? '',
  stat: firstBot?.statOrder[0] ?? '',
  currentLevel: 0,
  targetLevel: 10,
}

function findBot(key: string): BotEntry | undefined {
  return BOTS.find(bot => bot.key === key)
}

/** A stat's own ceiling, from its level table — never the shared ladder's length. */
function statCeiling(botName: string, statName: string): number {
  const bot = findBotByName(botName)
  return bot ? botStatMaxLevel(bot, statName) : 0
}

export const botUpgradeCalculator: CalculatorBuilder<BotUpgradeInput, BotUpgradeResult> = {
  id: 'bot.upgrade',
  title: 'Bot upgrade',
  summary: 'Medals to take one bot stat from its current level to a target.',

  fields: [
    {
      key: 'bot',
      label: 'Bot',
      kind: 'select',
      options: BOTS.map(bot => ({ value: bot.key, label: bot.label })),
    },
    {
      key: 'stat',
      label: 'Stat',
      kind: 'select',
      options: [...new Set(BOTS.flatMap(bot => bot.statOrder))].map(stat => ({ value: stat, label: stat })),
      help: 'Stats differ per bot — read `statsForBot` off the result to narrow this list.',
    },
    { key: 'currentLevel', label: 'Current Level', kind: 'number', min: 0 },
    { key: 'targetLevel', label: 'Target Level', kind: 'number', min: 0 },
  ],

  defaults,

  normalize(rawInput = {}) {
    const input = safeRecord(rawInput) as typeof rawInput

    const botKey = typeof input.bot === 'string' && findBot(input.bot) ? input.bot : defaults.bot
    const bot = findBot(botKey)
    const stat = typeof input.stat === 'string' && bot?.statOrder.includes(input.stat)
      ? input.stat
      : bot?.statOrder[0] ?? defaults.stat
    /*
     * The STAT's ceiling, not the ladder's length.
     *
     * All five bots share a 31-entry cost ladder and no stat uses all of it. Clamping to the
     * ladder sold 15 levels of Flame Bot Cooldown that do not exist and charged 14,700 medals for
     * them -- most of the reported total -- while the level rows came back with a null value each,
     * which is the only place it showed. The bots compartment has warned about exactly this since
     * 2026-08-17.
     */
    const cap = statCeiling(botKey, stat)
    return {
      bot: botKey,
      stat,
      currentLevel: Math.floor(clampNumber(input.currentLevel, 0, cap, 0)),
      targetLevel: Math.floor(clampNumber(input.targetLevel, 0, cap, Math.min(defaults.targetLevel, cap))),
    }
  },

  compute(rawInput = {}) {
    const input = this.normalize(rawInput)
    /* What the caller ASKED for, read safely: the notes compare it against the clamped value. */
    const asked = safeRecord(rawInput) as typeof rawInput
    const notes: string[] = []
    const bot = findBot(input.bot)
    const statsForBot = bot?.statOrder ?? []
    const maxLevel = statCeiling(input.bot, input.stat)

    const empty = {
      bot: input.bot,
      stat: input.stat,
      levels: [],
      totalMedals: 0,
      maxLevel,
      statsForBot,
    }

    if (!bot) return { ...empty, notes: [`No bot named "${input.bot}".`] }

    if (typeof asked.stat === 'string' && asked.stat && asked.stat !== input.stat) {
      notes.push(`${bot.label} has no stat named "${asked.stat}"; used ${input.stat} instead.`)
    }
    if (typeof asked.targetLevel === 'number' && asked.targetLevel > maxLevel) {
      notes.push(`${bot.label} ${input.stat} caps at level ${maxLevel}; the target was clamped.`)
    }
    if (input.targetLevel <= input.currentLevel) {
      notes.push('Target level is not above the current level, so there is nothing to buy.')
      return { ...empty, notes }
    }

    // The stat's own ladder, evaluated. It used to be a lookup into enumerated strings.
    const stat = bot.stats[input.stat]
    const levels: BotUpgradeLevel[] = []
    let totalMedals = 0

    for (let level = input.currentLevel + 1; level <= input.targetLevel; level += 1) {
      const medalCost = bot.costs[level] ?? 0
      totalMedals += medalCost
      levels.push({
        level,
        medalCost,
        value: stat && level <= stat.maxLevel ? formatBotStatValue(stat, level) : null,
      })
    }

    return { ...empty, levels, totalMedals, notes }
  },
}

/**
 * `EPD_MAXREND` — the maximum rend armour multiplier.
 *
 * Without the Rend Armor workshop unlock this is 1, not 0 — it multiplies
 * damage, so the identity is one.
 */
export function maxRendArmourMultiplier(input: {
  hasRend: boolean
  /** Max Rend Armor Multiplier lab level; a quarter a level. */
  labLevel: number
  substat: number
  enhancementLevel: number
}): number {
  if (!input.hasRend) return 1
  return (8 + input.substat + input.labLevel * 0.25) * (1 + input.enhancementLevel * 0.01)
}

/**
 * Selected Rend proc inputs under the documented community half-enhancement
 * interpretation, separately from the full-enhancement total cap above.
 * A dated owner example reports enhancement1.39 and about36% maxed chance
 * (30% * 1.195 = 35.85%); a June2026 reply explicitly says multiplier half
 * effective. This is a source-qualified composition, not native proof.
 * https://www.reddit.com/r/TheTowerGame/comments/1jgmrbl/
 * https://www.reddit.com/r/TheTowerGame/comments/1ucyi04/comment/ot7wkhe/
 *
 * Workshop chance and substat are fractions; the step is an additive damage
 * multiplier increment. Above-one chance returns null rather than guessing
 * extra procs or silently clipping. No buildup or current-cap grant occurs.
 */
export function rendArmorProcCoefficients(input: {
  hasRend: boolean; workshopChanceFraction: number; workshopAdditionalMultiplierPerProc: number
  chanceSubstatFraction: number; additionalMultiplierSubstat: number; enhancementLevel: number
}) {
  for (const value of [input.workshopChanceFraction, input.workshopAdditionalMultiplierPerProc,
    input.chanceSubstatFraction, input.additionalMultiplierSubstat, input.enhancementLevel]) {
    if (!Number.isFinite(value) || value < 0) throw new Error('REND_PROC_FINITE_NONNEGATIVE_INPUT_REQUIRED')
  }
  if (!Number.isSafeInteger(input.enhancementLevel)) throw new Error('REND_PROC_INTEGER_ENHANCEMENT_REQUIRED')
  const enhancementMultiplier = 1 + input.enhancementLevel * 0.005
  const chanceBeforeProcInterpretation = input.hasRend
    ? (input.workshopChanceFraction + input.chanceSubstatFraction) * enhancementMultiplier : 0
  const additionalMultiplierPerProc = input.hasRend
    ? (input.workshopAdditionalMultiplierPerProc + input.additionalMultiplierSubstat) * enhancementMultiplier : 0
  if (![enhancementMultiplier, chanceBeforeProcInterpretation, additionalMultiplierPerProc].every(Number.isFinite))
    throw new Error('REND_PROC_COEFFICIENT_OVERFLOW')
  return { chanceBeforeProcInterpretation, additionalMultiplierPerProc,
    chancePerProjectileHit: chanceBeforeProcInterpretation <= 1 ? chanceBeforeProcInterpretation : null,
    overOneChanceUnresolved: chanceBeforeProcInterpretation > 1,
    enhancementMultiplier, enhancementBasis: 'community_half_effect' as const }
}

/**
 * `EPD_SPB` — what the damage perk is worth.
 *
 * 15% a stack, raised by the Standard Perks Bonus lab. The eHP side writes the
 * same shape inline with its own per-stat rate.
 */
export function damagePerkMultiplier(
  hasPerk: boolean,
  standardPerksBonusLabLevel: number,
  quantity: number,
): number {
  if (!hasPerk) return 1
  return (1 + 0.15 * quantity) * (1 + standardPerksBonusLabLevel / 100)
}

/** The Area of Effect card's bonus by level — the sheet's own literal table. */
const AOE_CARD_LEVELS = [0.05, 0.08, 0.11, 0.14, 0.17, 0.2, 0.25]

/**
 * `EPD_AOE_CARD_BOOST` — the Area of Effect card's multiplier.
 *
 * Not a formula: the sheet indexes a literal seven-entry table, and the last
 * step is 5 points where every other step is 3.
 *
 * The level is clamped into the table rather than falling out of it. That is
 * the sheet's own behaviour at the bottom — `INDEX(table, 0)` yields the whole
 * table, which collapses to its first entry — and it is right for the game
 * too: an equipped card is at least level 1, so `hasCard` is what decides
 * whether the boost applies, not the level.
 */
export function areaOfEffectCardBoost(hasCard: boolean, cardLevel: number): number {
  if (!hasCard) return 1
  const index = Math.min(
    AOE_CARD_LEVELS.length - 1, Math.max(0, Math.floor(cardLevel) - 1),
  )
  return 1 + AOE_CARD_LEVELS[index]
}


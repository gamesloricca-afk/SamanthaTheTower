/**
 * Structural contradiction detection.
 *
 * ## The only kind worth automating
 *
 * Semantic contradiction between two prose claims is undecidable in practice.
 * Structural contradiction — two sources giving different values for the same
 * `(subject, predicate)` — is a `GROUP BY`, runs in microseconds, and is
 * exactly the shape of the defect this repo actually shipped:
 *
 * ```
 * (tier.22, coinBonus) = 72   [in-game,  v28.3]
 * (tier.22, coinBonus) = 75   [code,     unknown version]
 * ```
 *
 * That sat in the catalog for months. It was plausible, monotonic, and only
 * observable to accounts at tier 22+. No test pinned it because nobody thought
 * to. This module is what makes that class of defect loud by default rather
 * than by foresight.
 *
 * ## What it deliberately does not do
 *
 * It does not resolve disagreements by voting, averaging, or recency. It ranks
 * by source authority and reports. A human decides, because the losing value is
 * evidence that a source is unreliable — information worth more than the tidy
 * graph you would get by deleting it.
 */
/* ── file map ─────────────────────────────────────────────────────────────────
 * exports    collectAssertions, findContradictions, checkIncoming, contradictionsIn
 * depends    src/knowledge/substrate/schema, src/knowledge/substrate/types
 * used by    src/knowledge/substrate/index, src/knowledge/substrate/maturity
 * ─────────────────────────────────────────────── generated by `npm run map` ──
 */
import type { Assertion, ClaimOrigin, Compartment, KnowledgeGraph } from './types'
import { ORIGIN_AUTHORITY } from './schema'
import type { Contradiction } from './types'

function authorityRank(origin: ClaimOrigin): number {
  const index = ORIGIN_AUTHORITY.indexOf(origin)
  return index === -1 ? ORIGIN_AUTHORITY.length : index
}

/**
 * Normalise a value before comparing.
 *
 * Numbers written as `72` and `"72"` are the same claim arriving from a JSON
 * import and a TypeScript literal; treating them as a contradiction would make
 * the detector cry wolf, and a detector that cries wolf gets muted.
 */
function normaliseValue(value: string | number | boolean): string {
  if (typeof value === 'number') return String(value)
  if (typeof value === 'boolean') return String(value)
  const trimmed = value.trim()
  const asNumber = Number(trimmed)
  return Number.isFinite(asNumber) && trimmed !== '' ? String(asNumber) : trimmed.toLowerCase()
}

/** Every assertion in the graph, flattened. */
export function collectAssertions(graph: KnowledgeGraph): readonly Assertion[] {
  return graph.compartments.flatMap(compartment =>
    compartment.nodes.flatMap(node => node.assertions ?? []))
}

/**
 * Find every `(subject, predicate)` asserted with more than one distinct value.
 *
 * Runs over the whole graph, so it catches disagreements *across* compartments
 * — which is where they hide. Two families each internally consistent and
 * mutually contradictory is the normal way this goes wrong.
 */
export function findContradictions(graph: KnowledgeGraph): readonly Contradiction[] {
  const buckets = new Map<string, Assertion[]>()

  for (const assertion of collectAssertions(graph)) {
    const key = `${assertion.subject}\u0000${assertion.predicate}`
    const bucket = buckets.get(key)
    if (bucket) bucket.push(assertion)
    else buckets.set(key, [assertion])
  }

  const contradictions: Contradiction[] = []

  for (const [key, assertions] of buckets) {
    const distinct = new Set(assertions.map(a => normaliseValue(a.value)))
    if (distinct.size < 2) continue

    const [subject, predicate] = key.split('\u0000')
    const claims = assertions
      .map(a => ({
        value: a.value,
        origin: a.provenance.origin,
        ref: a.provenance.ref,
        sourceVersion: a.provenance.sourceVersion,
        verifiedAt: a.provenance.verifiedAt,
        authorityRank: authorityRank(a.provenance.origin),
      }))
      .sort((left, right) => left.authorityRank - right.authorityRank)

    contradictions.push({
      subject,
      predicate,
      claims,
      likelyValue: claims[0].value,
      crossSource: new Set(claims.map(c => c.origin)).size > 1,
    })
  }

  return contradictions.sort((left, right) => left.subject.localeCompare(right.subject))
}

/**
 * Check one external assertion against what is already known.
 *
 * This is the import gate. A shared knowledge pack runs every incoming
 * assertion through here before anything is written, so a claim that conflicts
 * with locally-verified knowledge is flagged at the door rather than sitting in
 * the graph being plausible.
 */
export function checkIncoming(
  graph: KnowledgeGraph,
  incoming: Assertion,
): { conflicts: boolean, existing: readonly Assertion[], advice: string } {
  const existing = collectAssertions(graph).filter(a =>
    a.subject === incoming.subject && a.predicate === incoming.predicate)

  if (existing.length === 0) {
    return {
      conflicts: false,
      existing,
      advice: 'No local claim for this subject/predicate. Import as unverified and check it here '
        + 'before relying on it.',
    }
  }

  const incomingValue = normaliseValue(incoming.value)
  const disagreeing = existing.filter(a => normaliseValue(a.value) !== incomingValue)

  if (disagreeing.length === 0) {
    return { conflicts: false, existing, advice: 'Agrees with local knowledge.' }
  }

  const bestLocal = [...disagreeing]
    .sort((l, r) => authorityRank(l.provenance.origin) - authorityRank(r.provenance.origin))[0]
  const incomingRank = authorityRank(incoming.provenance.origin)
  const localRank = authorityRank(bestLocal.provenance.origin)

  return {
    conflicts: true,
    existing,
    advice: incomingRank < localRank
      ? `Incoming claim has HIGHER authority (${incoming.provenance.origin} beats `
        + `${bestLocal.provenance.origin}). Re-verify the local value before overwriting — but do `
        + 'not overwrite automatically.'
      : `Local claim has equal or higher authority (${bestLocal.provenance.origin}). Import as `
        + 'unverified and flag the disagreement; do not replace local knowledge.',
  }
}

/** Contradictions confined to a single compartment. */
export function contradictionsIn(
  graph: KnowledgeGraph,
  compartment: Compartment,
): readonly Contradiction[] {
  const subjects = new Set(compartment.nodes.flatMap(node =>
    (node.assertions ?? []).map(a => a.subject)))
  return findContradictions(graph).filter(c => subjects.has(c.subject))
}

/**
 * The module's stat multiplier for a rarity and level.
 *
 * The rarity label is normalised with `findRarityLabel` before anything else.
 * Until 2026-08-17 this did a raw key lookup, so `Ancestral 5*` — the spelling
 * the Effective Paths sheet uses — returned 1 while `Ancestral 5` returned
 * 30.328. `getLevelCapForRarity` accepted both, so a caller could validate a
 * label successfully and then compute a module worth nothing, with no error at
 * either step.
 *
 * Every rarity lookup in this package now goes through the one normaliser.
 * Returning 1 for a label that is genuinely unknown is still correct and still
 * happens — what no longer happens is returning it for a real rarity spelled a
 * different way.
 */
export function computeModuleStat(opts: { type: ModuleCalcType; rarityLabel: string; level: number; primaryLabLevel?: number }): number {
  const primaryLabLevel = opts.primaryLabLevel === undefined ? 0 : opts.primaryLabLevel
  if (!Number.isInteger(primaryLabLevel) || primaryLabLevel < 0 || primaryLabLevel > 30) {
    throw new RangeError('primaryLabLevel must be an integer from 0 to 30')
  }
  // The primary-module lab scales only the bonus, preserving the neutral 1.
  const primaryBonusMultiplier = 1 + 0.01 * primaryLabLevel
  const { type } = opts
  const level = Math.max(1, Math.floor(Number(opts.level) || 1))
  const rarityLabel = findRarityLabel(opts.rarityLabel)
  if (!rarityLabel) return 1
  const base = MODULE_MULTIPLIER_BASE[type]?.[rarityLabel]
  if (base === undefined) return 1
  const increments = MODULE_MULTIPLIER_INCREMENT[type]
  const range = increments.find(entry => level >= entry.start && level <= entry.end)
  if (!range) return 1 + base * primaryBonusMultiplier
  const increment = range.base + range.increment * (level - range.start)
  let result = base + increment
  const match = /Ancestral (\d)/.exec(rarityLabel)
  if (match) {
    const steps = Number.parseInt(match[1], 10)
    result *= 1 + 0.04 * steps
  }
  return 1 + (Math.round(result * 1000) / 1000) * primaryBonusMultiplier
}

/**
 * Recover the rarity label that produces a known module bonus at a level.
 *
 * Effective Paths often prints only the base tier in `AM5` / `AP5` (e.g.
 * `"Ancestral"`) while `MODSTAT_*` uses the full Ancestral star count. The
 * computed bonus cell (`AM23` / `AO23`) still encodes the stars, so invert
 * `computeModuleStat` against it when the printed label is incomplete.
 *
 * Prefers an exact match. When several Ancestral* labels collide (they share
 * the same base multiplier until stars apply), the highest star that still
 * matches wins — that is the label the sheet's bonus cell implies.
 */
export function inferModuleRarityFromBonus(opts: {
  type: ModuleCalcType
  level: number
  bonus: number
  hint?: string | null
  primaryLabLevel?: number
}): ModuleRarity | undefined {
  const level = Math.max(1, Math.floor(Number(opts.level) || 1))
  const bonus = Number(opts.bonus)
  if (!Number.isFinite(bonus) || bonus <= 0) return undefined

  const hint = findRarityLabel(opts.hint)
  if (hint) {
    const atHint = computeModuleStat({ type: opts.type, rarityLabel: hint, level, primaryLabLevel: opts.primaryLabLevel })
    if (Math.abs(atHint - bonus) < 1e-9) return hint
  }

  let match: ModuleRarity | undefined
  for (const label of MODULE_RARITIES) {
    const value = computeModuleStat({ type: opts.type, rarityLabel: label, level, primaryLabLevel: opts.primaryLabLevel })
    if (Math.abs(value - bonus) < 1e-9) match = label
  }
  return match
}

export function normalizeModuleTypeForCalc(appType: 'cannon' | 'defense' | 'generator' | 'core'): ModuleCalcType {
  return appType === 'defense' ? 'armor' : appType
}
